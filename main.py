def make_sound(f1, f2, duration, volume=0.3, noise=False):
    rate = 44100
    n = int(rate * duration)
    buf = array.array("h")
    phase = 0.0
    for i in range(n):
        t = i / n
        phase += 2 * math.pi * (f1 + (f2 - f1) * t) / rate
        s = math.sin(phase)
        if noise:
            s = 0.6 * random.uniform(-1, 1) + 0.4 * s
        buf.append(int(s * (1 - t) * volume * 32767))
    return pygame.mixer.Sound(buffer=buf.tobytes())


