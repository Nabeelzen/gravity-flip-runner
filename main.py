def draw_pickup(pk):
    r = pk["rect"]
    cx, cy = r.center
    t = pygame.time.get_ticks()
    if pk["kind"] == "coin":
        w = max(4, int(22 * abs(math.cos(t / 250 + r.x * 0.03))))
        pygame.draw.ellipse(canvas, (255, 200, 50), (cx - w // 2, r.y, w, r.height))
        if w > 10:
            pygame.draw.ellipse(canvas, (255, 235, 130),
                                (cx - w // 2 + 3, r.y + 3, w - 6, r.height - 6))
    else:
        color = (80, 160, 255) if pk["kind"] == "shield" else (190, 110, 255)
        radius = 16 + int(2 * math.sin(t / 200))
        pygame.draw.circle(canvas, (25, 25, 50), (cx, cy), radius)
        pygame.draw.circle(canvas, color, (cx, cy), radius, 2)
        if pk["kind"] == "shield":
            draw_shield_icon(cx, cy, color)
        else:
            draw_clock_icon(cx, cy, color)

